"""Results pages and the claims graph, written by `opsci map build`.

A result is a node of ``type: result``: one scientific result (a figure, a table, a value, a
statement, a concept, or an assumption taken as given), in its own file
``tasks/<id>/results/<result-id>.md`` or, for a result that draws on several tasks,
``results/<result-id>.md``. Its header says where the result is stored (``artifacts``), the
code that made it (``code``), the results and nodes it rests on (``depends_on``) and the
external works it uses (``uses``, keys in ``citations/used.bib``).

Generated from the headers:

- ``tasks/<id>/results/README.md``: the task's results, with their figures;
- ``results/README.md``: the milestone results of the project (``milestone: true``, and every
  result under ``results/``);
- ``map/claims.md``: the claims graph, what every result rests on and what uses it, with the
  results that rest on failed or superseded work listed first.
"""

from __future__ import annotations

import os
import re
import subprocess
from pathlib import Path, PurePosixPath

from .nodes import DEAD_STATUSES, SUBROOTS, TASK_ROOTS, Node, Problem, ScanResult

BANNER = "<!-- GENERATED by `opsci map build` from the node headers. Do not edit this file; edit the headers. -->"
BIB = "citations/used.bib"
IMAGE_SUFFIXES = (".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp")
VERIFICATION_RANK = {"unverified": 0, "verified": 1, "human-verified": 2}
# Paths that are git-ignored by design: a missing file there is a warning, not an error.
UNTRACKED_ROOTS = ("data/",)

STATUS_STYLE = {
    "active": "fill:#dbeafe,stroke:#1d4ed8",
    "done": "fill:#dcfce7,stroke:#15803d",
    "paused": "fill:#fef9c3,stroke:#a16207",
    "failed": "fill:#fee2e2,stroke:#b91c1c",
    "superseded": "fill:#e5e7eb,stroke:#4b5563",
    "abandoned": "fill:#e5e7eb,stroke:#4b5563,stroke-dasharray:4",
}
AT_RISK_STYLE = "stroke:#dc2626,stroke-width:3px"


# ---------------------------------------------------------------- where results live

def task_of(path: str) -> str | None:
    """The task directory (``tasks/<id>``, ``brainstorm/tasks/<id>``) a file lies in, or None."""
    p = PurePosixPath(path)
    for i in range(1, len(p.parts) - 1):
        if "/".join(p.parts[:i]) in TASK_ROOTS:
            return "/".join(p.parts[:i + 1])
    return None


def results_dir(path: str) -> str | None:
    """The results directory holding a result file directly (``tasks/<id>/results`` or
    ``results``), or None."""
    parent = PurePosixPath(path).parent
    if parent.name != "results":
        return None
    d = parent.as_posix()
    if d == "results" or task_of(path) == parent.parent.as_posix():
        return d
    return None


def is_milestone(n: Node) -> bool:
    return n.get("type") == "result" and (bool(n.get("milestone")) or results_dir(n.path) == "results")


def results(nodes: list[Node]) -> list[Node]:
    return sorted((n for n in nodes if n.get("type") == "result"), key=lambda n: n.id)


# ---------------------------------------------------------------- citations

def read_bib(root: Path) -> dict[str, str]:
    """Key -> title (or '' if none) of every entry in citations/used.bib."""
    p = Path(root) / BIB
    if not p.is_file():
        return {}
    text = p.read_text(encoding="utf-8", errors="replace")
    out = {}
    starts = [(m.start(), m.group(1)) for m in re.finditer(r"@\w+\s*[{(]\s*([^,\s]+)\s*,", text)]
    for i, (pos, key) in enumerate(starts):
        body = text[pos:starts[i + 1][0] if i + 1 < len(starts) else len(text)]
        m = re.search(r"\btitle\s*=\s*[{\"](.*?)[}\"]\s*,?\s*\n", body, re.S | re.I)
        out[key] = re.sub(r"[{}]", "", " ".join(m.group(1).split())) if m else ""
    return out


# ---------------------------------------------------------------- checks

def check(root: Path, res: ScanResult) -> None:
    """Errors for result fields that point nowhere; warnings for results that rest on dead
    work, and for stored results that changed after their result file."""
    root = Path(root)
    bib = read_bib(root)
    ids = res.by_id()
    for n in res.nodes:
        for key in ("artifacts", "code"):
            for f in n.get(key, []) or []:
                if (root / f).exists():
                    continue
                if f.startswith(UNTRACKED_ROOTS):
                    res.warnings.append(Problem(n.path, f"{key}: '{f}' is not in this checkout (git-ignored data)"))
                else:
                    res.errors.append(Problem(n.path, f"{key}: '{f}' does not exist"))
        for k in n.get("uses", []) or []:
            if k not in bib:
                res.errors.append(Problem(n.path, f"uses: '{k}' is not a key in {BIB}"))
        if n.get("type") != "result":
            for key in ("kind", "milestone"):
                if key in n.header:
                    res.errors.append(Problem(n.path, f"{key}: only a result (type: result) has it"))
    for n in results(res.nodes):
        for line in at_risk(n, ids):
            res.warnings.append(Problem(n.path, line + ": check the result, then update it or mark it superseded"))
    for n, f in changed_after(root, results(res.nodes)):
        res.warnings.append(Problem(n.path, f"'{f}' changed after this result file was last committed: "
                                    "check the result still holds, then update the file"))


def at_risk(n: Node, ids: dict[str, Node]) -> list[str]:
    """Why a live result may no longer hold: each dead node it rests on, directly or through
    other nodes, and a dead task that holds it. Empty for a dead result."""
    if n.get("status") in DEAD_STATUSES:
        return []
    out = []
    by = superseded_by(ids.values())
    for d, via in ancestors(n, ids):
        a = ids[d]
        if a.get("status") in DEAD_STATUSES:
            how = f"rests on {d}" + (f" (through {via})" if via != n.id else "")
            repl = f" (by {', '.join(by[d])})" if by.get(d) else ""
            out.append(f"{how}, which is {a.get('status')}{repl}")
    t = home_task(n, ids)
    if t is not None and t.get("status") in DEAD_STATUSES and t.id not in dict(ancestors(n, ids)):
        out.append(f"its task {t.id} is {t.get('status')}")
    return out


def ancestors(n: Node, ids: dict[str, Node]) -> list[tuple[str, str]]:
    """(id, the direct dependency of ``n`` it is reached through) for every node ``n`` rests
    on, nearest first."""
    seen, order = {}, []
    frontier = [(d, d) for d in n.get("depends_on", []) or [] if d in ids]
    while frontier:
        nxt = []
        for d, via in frontier:
            if d in seen or d == n.id:
                continue
            seen[d] = via
            order.append((d, via if via != d else n.id))
            nxt += [(e, via) for e in ids[d].get("depends_on", []) or [] if e in ids]
        frontier = nxt
    return order


def superseded_by(nodes) -> dict[str, list[str]]:
    by: dict[str, list[str]] = {}
    for m in nodes:
        for s in m.get("supersedes", []) or []:
            by.setdefault(s, []).append(m.id)
    return {k: sorted(v) for k, v in by.items()}


def home_task(n: Node, ids: dict[str, Node]) -> Node | None:
    """The task node whose directory holds the result file."""
    t = task_of(n.path)
    if t is None:
        return None
    task = ids.get(PurePosixPath(t).name)
    return task if task is not None and task.path == t + "/context.md" else None


def weakest(n: Node, ids: dict[str, Node]) -> str:
    """The lowest verification level among the result and the results it rests on."""
    levels = [n.get("verification", "unverified")] + [
        ids[d].get("verification", "unverified") for d, _ in ancestors(n, ids) if ids[d].get("type") == "result"]
    return min(levels, key=lambda v: VERIFICATION_RANK.get(v, 0))


def _git_time(root: Path, path: str) -> int | None:
    r = subprocess.run(["git", "-C", str(root), "log", "-1", "--format=%ct", "--", path],
                       capture_output=True, text=True)
    return int(r.stdout.strip()) if r.returncode == 0 and r.stdout.strip() else None


def changed_after(root: Path, rs: list[Node]) -> list[tuple[Node, str]]:
    """(result, artifact) for every committed artifact whose last commit is newer than the
    result file's, or that has uncommitted changes while the result file has none. Empty
    outside a git work tree."""
    rs = [n for n in rs if n.get("artifacts") and n.get("status") not in DEAD_STATUSES]
    if not rs:
        return []
    try:
        inside = subprocess.run(["git", "-C", str(root), "rev-parse", "--show-prefix"],
                                capture_output=True, text=True)
    except FileNotFoundError:
        return []
    if inside.returncode != 0 or inside.stdout.strip():
        return []  # not a git work tree, or root is not its top: dates would mix projects
    st = subprocess.run(["git", "-C", str(root), "status", "--porcelain", "-z"], capture_output=True, text=True)
    dirty = {e[3:] for e in st.stdout.split("\0") if len(e) > 3}
    out = []
    for n in rs:
        mine = _git_time(root, n.path)
        for f in n.get("artifacts"):
            if f.startswith(UNTRACKED_ROOTS) or n.path in dirty:
                continue
            t = _git_time(root, f)
            if f in dirty or (t is not None and mine is not None and t > mine):
                out.append((n, f))
    return out


# ---------------------------------------------------------------- rendering helpers

def _rel(target: str, page_dir: str) -> str:
    return os.path.relpath(target, page_dir or ".").replace(os.sep, "/")


def _cell(text) -> str:
    return str(text or "").replace("|", "\\|").replace("\n", " ")


def _label(text) -> str:
    return str(text or "").replace('"', "#quot;").replace("\n", " ")


def _mid(node_id: str) -> str:
    return "n_" + node_id.replace("-", "_")


def _bid(key: str) -> str:
    return "b_" + re.sub(r"[^A-Za-z0-9_]", "_", key)


def _file(path: str, page_dir: str, linked) -> str:
    """A path, linked from ``page_dir`` if it is published (``linked`` is None or holds it)."""
    if linked is not None and path not in linked:
        return f"`{path}` (not published)"
    return f"[`{path}`]({_rel(path, page_dir)})"


def _node(i: str, ids: dict[str, Node], page_dir: str, linked) -> str:
    n = ids[i]
    if linked is not None and n.path not in linked:
        return f"{i} (not published)"
    return f"[{i}]({_rel(n.path, page_dir)})"


def _meta(n: Node) -> str:
    bits = [n.get("kind", "result"), n.get("status"), n.get("verification", "unverified")]
    return " · ".join(bits) + (" · milestone" if is_milestone(n) else "")


def _nodes(idlist, ids: dict[str, Node], page_dir: str, linked) -> str:
    """The ids that are nodes of this graph, linked; others (hard-private in an export) are left out."""
    return ", ".join(_node(i, ids, page_dir, linked) for i in idlist or [] if i in ids)


def _card(n: Node, ids: dict[str, Node], page_dir: str, linked) -> list[str]:
    """One result, as a section of a results page."""
    out = [f"## {n.id}: {n.get('title')}", "", f"*{_meta(n)}*", "", str(n.get("summary", "")).strip(), ""]
    for f in n.get("artifacts", []) or []:
        if f.lower().endswith(IMAGE_SUFFIXES) and (linked is None or f in linked):
            out += [f"![{n.id}]({_rel(f, page_dir)})", ""]
    rows = []
    if n.get("artifacts"):
        rows.append(("stored in", ", ".join(_file(f, page_dir, linked) for f in n.get("artifacts"))))
    if n.get("code"):
        rows.append(("code", ", ".join(_file(f, page_dir, linked) for f in n.get("code"))))
    t = home_task(n, ids)
    if t is not None:
        rows.append(("task", _node(t.id, ids, page_dir, linked)))
    if _nodes(n.get("depends_on"), ids, page_dir, linked):
        rows.append(("rests on", _nodes(n.get("depends_on"), ids, page_dir, linked)))
    if n.get("uses"):
        rows.append(("uses", ", ".join(f"[@{k}]" for k in n.get("uses"))))
    used = sorted(m.id for m in ids.values() if n.id in (m.get("depends_on") or []))
    if used:
        rows.append(("used by", _nodes(used, ids, page_dir, linked)))
    if n.get("evidence"):
        rows.append(("evidence", _file(n.get("evidence"), page_dir, linked)))
    rows.append(("full description", _node(n.id, ids, page_dir, linked)))
    risk = at_risk(n, ids)
    if risk:
        out += ["> **May no longer hold:** " + "; ".join(risk) + ".", ""]
    out += ["| | |", "|---|---|"] + [f"| {k} | {v} |" for k, v in rows] + [""]
    return out


def _withdrawn(dead: list[Node], ids: dict[str, Node], page_dir: str, linked) -> list[str]:
    if not dead:
        return []
    by = superseded_by(ids.values())
    out = ["## Withdrawn", "", "Results that failed, were superseded or were abandoned. They are kept so that",
           "nobody relies on them by mistake.", "", "| result | status | why | superseded by |", "|---|---|---|---|"]
    for n in dead:
        repl = _nodes(by.get(n.id), ids, page_dir, linked)
        out.append(f"| {_node(n.id, ids, page_dir, linked)} | {n.get('status')} | {_cell(n.get('summary'))} | {repl} |")
    return out + [""]


def _page(title: str, intro: list[str], rs: list[Node], ids, page_dir, linked, empty: str) -> str:
    live = [n for n in rs if n.get("status") not in DEAD_STATUSES]
    dead = [n for n in rs if n.get("status") in DEAD_STATUSES]
    out = [BANNER, "", f"# {title}", ""] + intro + [""]
    if not rs:
        return "\n".join(out + [empty, ""])
    for n in live:
        out += _card(n, ids, page_dir, linked)
    out += _withdrawn(dead, ids, page_dir, linked)
    return "\n".join(out)


# ---------------------------------------------------------------- the pages

def render_task_results(task: Node, nodes: list[Node], linked=None) -> str:
    tdir = task.path.rsplit("/", 1)[0]
    page_dir = tdir + "/results"
    ids = {n.id: n for n in nodes}
    rs = [n for n in results(nodes) if results_dir(n.path) == page_dir]
    intro = ["The scientific results of this task: the figures, tables, values and statements it",
             "established, not the plots and numbers of debugging runs. Each result has its own file",
             "here, `<result-id>.md`, with a `type: result` header (fields: `tasks/README.md`). This page",
             f"is generated from those headers. What each result rests on, across the project: "
             f"[the claims graph]({_rel(_claims_path(tdir), page_dir)})."]
    return _page(f"Results: {task.get('title')}", intro, rs, ids, page_dir, linked, "No results yet.")


def render_project_results(nodes: list[Node], linked=None) -> str:
    ids = {n.id: n for n in nodes}
    rs = [n for n in results(nodes) if is_milestone(n) and not n.path.startswith(tuple(s + "/" for s in SUBROOTS))]
    intro = ["The milestone results of the project: the results a paper on it would report. A result",
             "is listed here if its header says `milestone: true`, or if its file is in this directory",
             "(a result that draws on several tasks). Every task lists all of its results in",
             "`tasks/<id>/results/README.md`. What each result rests on: [the claims graph](../map/claims.md)."]
    return _page("Results", intro, rs, ids, "results", linked, "No milestone results yet.")


def _claims_path(tdir: str) -> str:
    first = tdir.split("/", 1)[0]
    return f"{first}/map/claims.md" if first in SUBROOTS else "map/claims.md"


def render_claims(nodes: list[Node], linked=None, bib=None, page_dir: str = "map") -> str:
    """The claims graph of ``nodes``: every result, the nodes and external works it rests on,
    the tasks it came from, and the nodes that use it."""
    bib = bib or {}
    ids = {n.id: n for n in nodes}
    rs = results(nodes)
    out = [BANNER, "", "# Claims graph", ""]
    if not rs:
        return "\n".join(out + ["No results yet. A result is a file with a `type: result` header, in",
                                "`tasks/<id>/results/` (see `tasks/README.md`).", ""])
    out += [
        "The logic of the project's results. Arrows: `A --> B` means result B rests on A (a result,",
        "a task, a dataset, or an external work from `citations/used.bib`). Each result sits in a box",
        "with the task it came from. Dotted arrows point from a new result to the one it supersedes.",
        "Colour shows the status; a thick red border marks a result that rests on failed, superseded",
        "or abandoned work and may no longer hold.",
    ]
    # the nodes drawn: results, what they rest on, and what uses them
    drawn = {n.id for n in rs}
    for n in rs:
        drawn |= {d for d in n.get("depends_on", []) or [] if d in ids}
    users = sorted({m.id for m in nodes for d in m.get("depends_on", []) or [] if d in {r.id for r in rs}})
    drawn |= set(users)
    keys = sorted({k for n in rs for k in n.get("uses", []) or []})
    boxes: dict[str, list[Node]] = {}
    loose = []
    for n in rs:
        t = home_task(n, ids)
        boxes.setdefault(t.id if t else ("results" if results_dir(n.path) == "results" else ""), []).append(n)
    out += ["", "```mermaid", "flowchart LR"]
    if keys:
        out.append('  subgraph lit["External works (citations/used.bib)"]')
        for k in keys:
            title = bib.get(k, "")
            out.append(f'    {_bid(k)}["{_label(k)}' + (f"<br/>{_label(title[:60])}" if title else "") + '"]')
        out.append("  end")
    for box in sorted(boxes):
        members = boxes[box]
        if box == "":
            loose += members
            continue
        if box == "results":
            out.append('  subgraph project_results["project-level results"]')
        else:
            out.append(f'  subgraph {_mid(box)}["task {_label(box)}: {_label(ids[box].get("title"))}"]')
        for n in members:
            out.append(f'    {_mid(n.id)}["{_label(n.id)}: {_label(n.get("title"))}<br/>{_meta(n)}"]')
        out.append("  end")
    for n in loose:
        out.append(f'  {_mid(n.id)}["{_label(n.id)}: {_label(n.get("title"))}<br/>{_meta(n)}"]')
    boxed = {b for b in boxes if b not in ("", "results")}
    for i in sorted(drawn - {n.id for n in rs} - boxed):
        m = ids[i]
        out.append(f'  {_mid(i)}["{_label(i)}: {_label(m.get("title"))}<br/>{m.get("type")} · {m.get("status")}"]')
    for n in rs + [ids[u] for u in users if ids[u].get("type") != "result"]:
        own = home_task(n, ids)
        for d in n.get("depends_on", []) or []:
            if d in drawn | boxed and not (own is not None and d == own.id):  # not from its own box
                out.append(f"  {_mid(d)} --> {_mid(n.id)}")
        for k in n.get("uses", []) or []:
            out.append(f"  {_bid(k)} --> {_mid(n.id)}")
        for s in n.get("supersedes", []) or []:
            if s in drawn:
                out.append(f"  {_mid(n.id)} -.->|supersedes| {_mid(s)}")
    shown = [ids[i] for i in sorted(drawn - boxed)]
    for status, style in STATUS_STYLE.items():
        members = [_mid(n.id) for n in shown if n.get("status") == status]
        if members:
            out += [f"  classDef {status} {style}", f"  class {','.join(members)} {status}"]
    risky = [n for n in rs if at_risk(n, ids)]
    if risky:
        out += [f"  classDef atrisk {AT_RISK_STYLE}", f"  class {','.join(_mid(n.id) for n in risky)} atrisk"]
    out += ["```", ""]

    out += ["## May no longer hold", ""]
    if risky:
        out += ["These live results rest on work that failed or was replaced. Check each one, then",
                "update it (its `depends_on`, its file) or set its status to `superseded` or `failed`.", ""]
        for n in risky:
            out.append(f"- {_node(n.id, ids, page_dir, linked)}: " + "; ".join(at_risk(n, ids)) + ".")
    else:
        out.append("None: every live result rests only on live work.")
    out.append("")
    weak = [n for n in rs if n.get("status") not in DEAD_STATUSES
            and n.get("verification", "unverified") != "unverified" and weakest(n, ids) == "unverified"]
    if weak:
        out += ["## Verified, but resting on unverified results", ""]
        for n in weak:
            un = [d for d, _ in ancestors(n, ids) if ids[d].get("type") == "result"
                  and ids[d].get("verification", "unverified") == "unverified"]
            out.append(f"- {_node(n.id, ids, page_dir, linked)} ({n.get('verification')}) rests on "
                       + _nodes(un, ids, page_dir, linked) + ".")
        out.append("")

    out += ["## Results", "",
            "`chain` is the lowest verification level among the result and every result it rests on.", "",
            "| result | kind | status | verification | chain | statement | task | stored in | code | rests on | used by |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for n in rs:
        t = home_task(n, ids)
        rests = [_node(d, ids, page_dir, linked) for d in n.get("depends_on", []) or [] if d in ids] + \
                [f"[@{k}]" for k in n.get("uses", []) or []]
        used = sorted(m.id for m in nodes if n.id in (m.get("depends_on") or []))
        out.append(" | ".join([
            f"| {_node(n.id, ids, page_dir, linked)}", n.get("kind", "result"), str(n.get("status")),
            n.get("verification", "unverified"), weakest(n, ids), _cell(n.get("summary")),
            _node(t.id, ids, page_dir, linked) if t else "",
            ", ".join(_file(f, page_dir, linked) for f in n.get("artifacts", []) or []),
            ", ".join(_file(f, page_dir, linked) for f in n.get("code", []) or []),
            ", ".join(rests), _nodes(used, ids, page_dir, linked)]) + " |")
    out.append("")
    if keys:
        out += ["## External works", "", "| key | title | used by |", "|---|---|---|"]
        for k in keys:
            by = [n.id for n in rs if k in (n.get("uses") or [])]
            out.append(f"| [@{k}] | {_cell(bib.get(k, ''))} | {_nodes(by, ids, page_dir, linked)} |")
        out.append("")
    return "\n".join(out)


def outputs(nodes: list[Node], root_has, linked=None, bib=None) -> dict[str, str]:
    """The generated result files: the claims graph (and one per sub-root that exists), the
    project results page, and one results page per task."""
    out = {"map/claims.md": render_claims(nodes, linked, bib),
           "results/README.md": render_project_results(nodes, linked)}
    for sub in SUBROOTS:
        if root_has(sub):
            pre = sub + "/"
            mine = [n for n in nodes if n.path.startswith(pre)]
            out[f"{sub}/map/claims.md"] = render_claims(mine, linked, bib, page_dir=f"{sub}/map")
    for n in nodes:
        if n.get("type") == "task" and task_of(n.path) and n.path.endswith("/context.md") \
                and n.path.count("/") == task_of(n.path).count("/") + 1:
            rel = f"{task_of(n.path)}/results/README.md"
            if linked is None or rel in linked:
                out[rel] = render_task_results(n, nodes, linked)
    return out
